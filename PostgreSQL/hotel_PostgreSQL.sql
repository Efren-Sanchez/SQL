-- 5. CONSULTAS DE PRUEBA
-- -----------------------------------------------------------------------------

-- A. Resumen de cuenta del cliente (Alojamiento + Extras)
SELECT 
    r.id_reserva,
    h.nombre || ' ' || h.apellidos AS cliente,
    r.total_alojamiento AS base_habitacion,
    COALESCE(SUM(ce.subtotal), 0) AS total_servicios,
    r.total_alojamiento + COALESCE(SUM(ce.subtotal), 0) AS factura_total
FROM reservas r
JOIN huespedes h ON r.id_huesped = h.id_huesped
LEFT JOIN consumos_extras ce ON r.id_reserva = ce.id_reserva
GROUP BY r.id_reserva, h.nombre, h.apellidos
LIMIT 10;

-- B. Ingresos por país (Solo reservas Finalizadas)
SELECT 
    h.pais, 
    COUNT(r.id_reserva) as num_reservas,
    SUM(r.total_alojamiento) as ingresos_hospedaje
FROM huespedes h
JOIN reservas r ON h.id_huesped = r.id_huesped
WHERE r.estado_reserva = 'Finalizada'
GROUP BY h.pais
ORDER BY ingresos_hospedaje DESC;

-- C. Servicios más populares
SELECT s.nombre, COUNT(ce.id_consumo) as veces_solicitado
FROM servicios s
LEFT JOIN consumos_extras ce ON s.id_servicio = ce.id_servicio
GROUP BY s.id_servicio
ORDER BY veces_solicitado DESC;