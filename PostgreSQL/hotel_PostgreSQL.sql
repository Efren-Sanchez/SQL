-- 1. LIMPIEZA DE ESTRUCTURAS
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS consumos_extras CASCADE;
DROP TABLE IF EXISTS servicios CASCADE;
DROP TABLE IF EXISTS reservas CASCADE;
DROP TABLE IF EXISTS habitaciones CASCADE;
DROP TABLE IF EXISTS tipos_habitacion CASCADE;
DROP TABLE IF EXISTS huespedes CASCADE;

DROP TYPE IF EXISTS estado_hab;
DROP TYPE IF EXISTS estado_res;

-- 2. DEFINICIÓN DE TIPOS PERSONALIZADOS (ENUMS)
-- -----------------------------------------------------------------------------
CREATE TYPE estado_hab AS ENUM ('Disponible', 'Ocupada', 'Limpieza', 'Mantenimiento');
CREATE TYPE estado_res AS ENUM ('Confirmada', 'Pendiente', 'Cancelada', 'Finalizada');

-- 3. DEFINICIÓN DEL ESQUEMA (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE tipos_habitacion (
    id_tipo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    precio_noche NUMERIC(10,2) NOT NULL,
    capacidad_personas SMALLINT NOT NULL,
    descripcion TEXT
);

CREATE TABLE habitaciones (
    id_habitacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(10) UNIQUE NOT NULL,
    id_tipo INT NOT NULL,
    piso SMALLINT NOT NULL,
    estado estado_hab DEFAULT 'Disponible',
    CONSTRAINT fk_hab_tipo FOREIGN KEY (id_tipo) REFERENCES tipos_habitacion(id_tipo)
);

CREATE TABLE huespedes (
    id_huesped INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    documento_id VARCHAR(20) UNIQUE NOT NULL,
    email VARCHAR(100),
    telefono VARCHAR(20),
    pais VARCHAR(50)
);

CREATE TABLE reservas (
    id_reserva INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_huesped INT NOT NULL,
    id_habitacion INT NOT NULL,
    fecha_reserva TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_entrada DATE NOT NULL,
    fecha_salida DATE NOT NULL,
    estado_reserva estado_res DEFAULT 'Pendiente',
    total_alojamiento NUMERIC(10,2) DEFAULT 0.00,
    CONSTRAINT fk_res_huesped FOREIGN KEY (id_huesped) REFERENCES huespedes(id_huesped),
    CONSTRAINT fk_res_hab FOREIGN KEY (id_habitacion) REFERENCES habitaciones(id_habitacion),
    CONSTRAINT chk_fechas CHECK (fecha_salida > fecha_entrada)
);

CREATE TABLE servicios (
    id_servicio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    precio NUMERIC(10,2) NOT NULL
);

CREATE TABLE consumos_extras (
    id_consumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva INT NOT NULL,
    id_servicio INT NOT NULL,
    fecha_consumo TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    cantidad SMALLINT DEFAULT 1,
    subtotal NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_cons_reserva FOREIGN KEY (id_reserva) REFERENCES reservas(id_reserva),
    CONSTRAINT fk_cons_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio)
);

