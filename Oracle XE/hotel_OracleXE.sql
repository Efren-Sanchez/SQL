-- 2. DEFINICIÓN DEL ESQUEMA (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE tipos_habitacion (
    id_tipo            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR2(50) NOT NULL,
    precio_noche       NUMBER(10,2) NOT NULL,
    capacidad_personas NUMBER(3) NOT NULL,
    descripcion        CLOB
);

CREATE TABLE habitaciones (
    id_habitacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero        VARCHAR2(10) NOT NULL UNIQUE,
    id_tipo       NUMBER NOT NULL,
    piso          NUMBER(3) NOT NULL,
    estado        VARCHAR2(20) DEFAULT 'Disponible',
    CONSTRAINT fk_hab_tipo FOREIGN KEY (id_tipo) REFERENCES tipos_habitacion(id_tipo),
    CONSTRAINT chk_estado_hab CHECK (estado IN ('Disponible', 'Ocupada', 'Limpieza', 'Mantenimiento'))
);

CREATE TABLE huespedes (
    id_huesped   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR2(50) NOT NULL,
    apellidos    VARCHAR2(100) NOT NULL,
    documento_id VARCHAR2(20) NOT NULL UNIQUE,
    email        VARCHAR2(100),
    telefono     VARCHAR2(20),
    pais         VARCHAR2(50)
);

CREATE TABLE reservas (
    id_reserva        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_huesped        NUMBER NOT NULL,
    id_habitacion     NUMBER NOT NULL,
    fecha_reserva     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_entrada     DATE NOT NULL,
    fecha_salida      DATE NOT NULL,
    estado_reserva    VARCHAR2(20) DEFAULT 'Pendiente',
    total_alojamiento NUMBER(10,2) DEFAULT 0.00,
    CONSTRAINT fk_res_huesped FOREIGN KEY (id_huesped) REFERENCES huespedes(id_huesped),
    CONSTRAINT fk_res_hab FOREIGN KEY (id_habitacion) REFERENCES habitaciones(id_habitacion),
    CONSTRAINT chk_fechas CHECK (fecha_salida > fecha_entrada),
    CONSTRAINT chk_estado_res CHECK (estado_reserva IN ('Confirmada', 'Pendiente', 'Cancelada', 'Finalizada'))
);

CREATE TABLE servicios (
    id_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(50) NOT NULL,
    precio      NUMBER(10,2) NOT NULL
);

CREATE TABLE consumos_extras (
    id_consumo    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva    NUMBER NOT NULL,
    id_servicio   NUMBER NOT NULL,
    fecha_consumo DATE DEFAULT SYSDATE,
    cantidad      NUMBER(3) DEFAULT 1,
    subtotal      NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_cons_reserva FOREIGN KEY (id_reserva) REFERENCES reservas(id_reserva),
    CONSTRAINT fk_cons_servicio FOREIGN KEY (id_servicio) REFERENCES servicios(id_servicio)
);

