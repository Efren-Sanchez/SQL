-- Inserción Masiva de Consumos Extras (150 registros)
BEGIN
    FOR i IN 1..150 LOOP
        DECLARE
            v_precio_serv NUMBER;
            v_id_serv     NUMBER := TRUNC(DBMS_RANDOM.VALUE(1, 6));
            v_cant        NUMBER := TRUNC(DBMS_RANDOM.VALUE(1, 4));
        BEGIN
            SELECT precio INTO v_precio_serv FROM servicios WHERE id_servicio = v_id_serv;
            
            INSERT INTO consumos_extras (id_reserva, id_servicio, cantidad, subtotal)
            VALUES (
                TRUNC(DBMS_RANDOM.VALUE(1, 121)), -- ID Reserva aleatoria
                v_id_serv,
                v_cant,
                v_precio_serv * v_cant
            );
        END;
    END LOOP;
END;
