-- 4. CONSULTAS DE PRUEBA
-- -----------------------------------------------------------------------------

-- A. Reporte de ocupación y total por reserva (Check-out)
SELECT 
    r.id_reserva, 
    h.nombre || ' ' || h.apellidos AS huesped, 
    r.total_alojamiento AS costo_estancia,
    NVL(SUM(ce.subtotal), 0) AS total_servicios,
    (r.total_alojamiento + NVL(SUM(ce.subtotal), 0)) AS gran_total
FROM reservas r
JOIN huespedes h ON r.id_huesped = h.id_huesped
LEFT JOIN consumos_extras ce ON r.id_reserva = ce.id_reserva
GROUP BY r.id_reserva, h.nombre, h.apellidos, r.total_alojamiento
FETCH FIRST 10 ROWS ONLY;

-- B. Habitaciones disponibles de tipo 'Suite' o 'Económica'
SELECT hab.numero, th.nombre as tipo, hab.piso
FROM habitaciones hab
JOIN tipos_habitacion th ON hab.id_tipo = th.id_tipo
WHERE hab.estado = 'Disponible';

-- C. Total recaudado por país de origen del huésped
SELECT h.pais, SUM(r.total_alojamiento) as total_ingresos
FROM huespedes h
JOIN reservas r ON h.id_huesped = r.id_huesped
GROUP BY h.pais
ORDER BY total_ingresos DESC;