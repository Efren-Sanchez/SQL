-- Visualizar activos asignados con sus dueños y correos
SELECT e.nombre || ' ' || e.apellidos AS empleado, 
       h.modelo, 
       h.n_serie, 
       u.nombre AS ubicacion
FROM asignaciones a
JOIN empleados e ON a.id_empleado = e.id_empleado
JOIN hardware h ON a.id_hardware = h.id_hardware
JOIN ubicaciones u ON h.id_ubicacion = u.id_ubicacion
WHERE a.fecha_devolucion IS NULL;