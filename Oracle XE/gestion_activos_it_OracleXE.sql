-- 1. LIMPIEZA DE TABLAS (Bloque PL/SQL para evitar errores si no existen)
BEGIN
   FOR r IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'MANTENIMIENTOS', 'ASIGNACIONES', 'LICENCIAS', 'HARDWARE', 
      'SOFTWARE', 'EMPLEADOS', 'CATEGORIAS', 'FABRICANTES', 'UBICACIONES'))
   LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || r.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
END;
/

-- 2. DEFINICIÓN DEL ESQUEMA (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE ubicaciones (
    id_ubicacion NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    edificio VARCHAR2(50),
    planta NUMBER(3)
);

CREATE TABLE fabricantes (
    id_fabricante NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    pais VARCHAR2(50),
    soporte_email VARCHAR2(100)
);

CREATE TABLE categorias (
    id_categoria NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    tipo VARCHAR2(10) NOT NULL,
    CONSTRAINT check_tipo_cat CHECK (tipo IN ('Hardware', 'Software'))
);

CREATE TABLE empleados (
    id_empleado NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    departamento VARCHAR2(50),
    email VARCHAR2(100) UNIQUE NOT NULL,
    CONSTRAINT check_dept CHECK (departamento IN ('IT', 'Ventas', 'RRHH', 'Finanzas', 'Marketing', 'Operaciones', 'Legal'))
);

CREATE TABLE software (
    id_software NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(150) NOT NULL,
    id_fabricante NUMBER(10),
    id_categoria NUMBER(10),
    version_soft VARCHAR2(20),
    CONSTRAINT fk_soft_fab FOREIGN KEY (id_fabricante) REFERENCES fabricantes(id_fabricante),
    CONSTRAINT fk_soft_cat FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria)
);

CREATE TABLE hardware (
    id_hardware NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo VARCHAR2(150) NOT NULL,
    n_serie VARCHAR2(50) UNIQUE NOT NULL,
    id_fabricante NUMBER(10),
    id_categoria NUMBER(10),
    fecha_compra DATE NOT NULL,
    costo NUMBER(12,2) NOT NULL,
    estado VARCHAR2(15) DEFAULT 'Stock',
    id_ubicacion NUMBER(10),
    CONSTRAINT check_estado CHECK (estado IN ('Stock', 'Asignado', 'Reparacion', 'Retirado')),
    CONSTRAINT fk_hard_fab FOREIGN KEY (id_fabricante) REFERENCES fabricantes(id_fabricante),
    CONSTRAINT fk_hard_cat FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria),
    CONSTRAINT fk_hard_ubi FOREIGN KEY (id_ubicacion) REFERENCES ubicaciones(id_ubicacion)
);

CREATE TABLE licencias (
    id_licencia NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_software NUMBER(10) NOT NULL,
    clave_activacion VARCHAR2(255) UNIQUE,
    fecha_expira DATE,
    tipo_licencia VARCHAR2(15),
    CONSTRAINT check_tipo_lic CHECK (tipo_licencia IN ('OEM', 'Retail', 'Suscripción', 'Volumen')),
    CONSTRAINT fk_lic_soft FOREIGN KEY (id_software) REFERENCES software(id_software)
);

CREATE TABLE asignaciones (
    id_asignacion NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado NUMBER(10) NOT NULL,
    id_hardware NUMBER(10) NULL,
    id_licencia NUMBER(10) NULL,
    fecha_entrega DATE NOT NULL,
    fecha_devolucion DATE NULL,
    comentarios VARCHAR2(500),
    CONSTRAINT fk_asig_emp FOREIGN KEY (id_empleado) REFERENCES empleados(id_empleado),
    CONSTRAINT fk_asig_hard FOREIGN KEY (id_hardware) REFERENCES hardware(id_hardware),
    CONSTRAINT fk_asig_lic FOREIGN KEY (id_licencia) REFERENCES licencias(id_licencia)
);

CREATE TABLE mantenimientos (
    id_mantenimiento NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hardware NUMBER(10) NOT NULL,
    fecha_servicio DATE NOT NULL,
    descripcion VARCHAR2(1000),
    costo_reparacion NUMBER(10,2) DEFAULT 0,
    tecnico VARCHAR2(100),
    CONSTRAINT fk_mante_hard FOREIGN KEY (id_hardware) REFERENCES hardware(id_hardware)
);

