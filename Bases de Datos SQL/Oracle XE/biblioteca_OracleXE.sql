-- 2. DEFINICIÓN DEL ESQUEMA DE TABLAS (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE autores (
    id_autor    NUMBER(10) NOT NULL,
    nombre      VARCHAR2(50) NOT NULL,
    apellido1   VARCHAR2(50),
    apellido2   VARCHAR2(50),
    nacionalidad VARCHAR2(50),
    fecha_nac   DATE NOT NULL,
    fecha_dep   DATE,
    CONSTRAINT pk_autores PRIMARY KEY (id_autor)
);

CREATE TABLE editoriales (
    id_editorial NUMBER(10) NOT NULL,
    nombre       VARCHAR2(100) NOT NULL,
    direccion    VARCHAR2(150),
    telefono     VARCHAR2(20),
    email        VARCHAR2(100),
    CONSTRAINT pk_editoriales PRIMARY KEY (id_editorial)
);

CREATE TABLE generos (
    id_genero NUMBER(10) NOT NULL,
    nombre    VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_generos PRIMARY KEY (id_genero)
);

CREATE TABLE libros (
    id_libro     NUMBER(10) NOT NULL,
    titulo       VARCHAR2(150) NOT NULL,
    id_autor     NUMBER(10) NOT NULL,
    id_editorial NUMBER(10) NOT NULL,
    fecha_pub    DATE NOT NULL,
    paginas      NUMBER(10) NOT NULL,
    id_genero    NUMBER(10) NOT NULL,
    isbn         VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_libros PRIMARY KEY (id_libro),
    CONSTRAINT fk_libros_autor FOREIGN KEY (id_autor) REFERENCES autores(id_autor),
    CONSTRAINT fk_libros_editorial FOREIGN KEY (id_editorial) REFERENCES editoriales(id_editorial),
    CONSTRAINT fk_libros_genero FOREIGN KEY (id_genero) REFERENCES generos(id_genero)
);

CREATE TABLE usuarios (
    id_usuario NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR2(50) NOT NULL,
    apellidos  VARCHAR2(100) NOT NULL,
    dni        VARCHAR2(15) NOT NULL,
    email      VARCHAR2(100),
    telefono   VARCHAR2(20),
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuarios_dni UNIQUE (dni)
);

CREATE TABLE empleados (
    id_empleado NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR2(50) NOT NULL,
    apellidos   VARCHAR2(100) NOT NULL,
    cargo       VARCHAR2(50),
    salario     NUMBER(10,2),
    CONSTRAINT pk_empleados PRIMARY KEY (id_empleado)
);

CREATE TABLE ejemplares (
    id_ejemplar NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_libro    NUMBER(10) NOT NULL,
    estado      VARCHAR2(20) DEFAULT 'Disponible',
    CONSTRAINT pk_ejemplares PRIMARY KEY (id_ejemplar),
    CONSTRAINT fk_ejemplares_libro FOREIGN KEY (id_libro) REFERENCES libros(id_libro),
    CONSTRAINT ck_estado_ejemplar CHECK (estado IN ('Disponible', 'Prestado', 'Reservado', 'Mantenimiento', 'Extraviado', 'Dañado'))
);

CREATE TABLE prestamos (
    id_prestamo             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_usuario              NUMBER(10) NOT NULL,
    id_ejemplar             NUMBER(10) NOT NULL,
    fecha_inicio            DATE NOT NULL,
    fecha_devolucion_prevista DATE NOT NULL,
    fecha_devolucion_real   DATE DEFAULT NULL,
    CONSTRAINT pk_prestamos PRIMARY KEY (id_prestamo),
    CONSTRAINT fk_prestamos_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_prestamos_ejemplar FOREIGN KEY (id_ejemplar) REFERENCES ejemplares(id_ejemplar)
);

CREATE TABLE reservas (
    id_reserva    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER(10) NOT NULL,
    id_libro      NUMBER(10) NOT NULL,
    fecha_reserva DATE NOT NULL,
    CONSTRAINT pk_reservas PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reservas_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_reservas_libro FOREIGN KEY (id_libro) REFERENCES libros(id_libro)
);

CREATE TABLE sanciones (
    id_sancion  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  NUMBER(10) NOT NULL,
    id_prestamo NUMBER(10) NOT NULL,
    motivo      VARCHAR2(255),
    monto       NUMBER(10,2),
    pagada      NUMBER(1) DEFAULT 0, -- Oracle no tiene BOOLEAN nativo en SQL, usamos 0/1
    fecha_pago  DATE DEFAULT NULL,
    CONSTRAINT pk_sanciones PRIMARY KEY (id_sancion),
    CONSTRAINT fk_sanciones_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_sanciones_prestamo FOREIGN KEY (id_prestamo) REFERENCES prestamos(id_prestamo),
    CONSTRAINT ck_sanciones_pagada CHECK (pagada IN (0, 1))
);

