WHERE s.pagada = 0;

-- 2. Resumen de stock
SELECT estado, COUNT(*) AS cantidad,
       ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM ejemplares), 2) || '%' AS porcentaje
FROM ejemplares
GROUP BY estado;