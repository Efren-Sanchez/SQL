-- 4. CONSULTAS DE PRUEBA (Sintaxis Oracle)
-- -----------------------------------------------------------------------------

-- A. Stock actual con nombre de marca y modelo
SELECT m.nombre AS marca, mo.nombre AS modelo, c.vin, c.precio_base, c.estado
FROM coches c
JOIN modelos mo ON c.id_modelo = mo.id_modelo
JOIN marcas m ON mo.id_marca = m.id_marca
WHERE c.estado = 'Disponible'
ORDER BY c.precio_base DESC;

-- B. Total de ventas por vendedor
SELECT v.nombre, v.apellidos, COUNT(ve.id_venta) AS total_unidades, SUM(ve.precio_final) AS total_euros
FROM vendedores v
LEFT JOIN ventas ve ON v.id_vendedor = ve.id_vendedor
GROUP BY v.id_vendedor, v.nombre, v.apellidos
ORDER BY total_euros DESC;

-- C. Gastos de taller por coche (Top 10 más caros)
SELECT * FROM (
    SELECT c.vin, mo.nombre AS modelo, SUM(r.coste) AS total_gastado
    FROM revisiones r
    JOIN coches c ON r.id_coche = c.id_coche
    JOIN modelos mo ON c.id_modelo = mo.id_modelo
    GROUP BY c.vin, mo.nombre
    ORDER BY total_gastado DESC
) WHERE ROWNUM <= 10;