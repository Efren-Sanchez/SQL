-- INSERCIÓN MASIVA DE COCHES (150 registros) usando un bloque PL/SQL
BEGIN
   FOR i IN 1..150 LOOP
      INSERT INTO coches (id_modelo, vin, color, anio, precio_base, estado, tipo, kilometraje)
      VALUES (
         TRUNC(DBMS_RANDOM.VALUE(1, 11)), -- Modelo aleatorio
         'VIN' || LPAD(i, 14, '0'),       -- VIN único
         CASE TRUNC(DBMS_RANDOM.VALUE(1, 6))
            WHEN 1 THEN 'Blanco' WHEN 2 THEN 'Negro' WHEN 3 THEN 'Gris' WHEN 4 THEN 'Rojo' ELSE 'Azul' END,
         TRUNC(DBMS_RANDOM.VALUE(2018, 2025)),
         TRUNC(DBMS_RANDOM.VALUE(15000, 60000)),
         CASE TRUNC(DBMS_RANDOM.VALUE(1, 5))
            WHEN 1 THEN 'Disponible' WHEN 2 THEN 'Vendido' WHEN 3 THEN 'Reservado' ELSE 'Mantenimiento' END,
         CASE WHEN DBMS_RANDOM.VALUE(0, 1) > 0.5 THEN 'Nuevo' ELSE 'Ocasión' END,
         CASE WHEN DBMS_RANDOM.VALUE(0, 1) > 0.7 THEN TRUNC(DBMS_RANDOM.VALUE(10000, 120000)) ELSE 0 END
      );
   END LOOP;
END;
/

-- INSERCIÓN MASIVA DE VENTAS (100 registros)
-- Solo para coches que marcamos arriba como 'Vendido'
BEGIN
   FOR rec IN (SELECT id_coche, precio_base FROM coches WHERE estado = 'Vendido' AND ROWNUM <= 100) LOOP
      INSERT INTO ventas (id_coche, id_cliente, id_vendedor, fecha_venta, precio_final, metodo_pago)
      VALUES (
         rec.id_coche,
         TRUNC(DBMS_RANDOM.VALUE(1, 4)), -- Cliente entre los 3 creados
         TRUNC(DBMS_RANDOM.VALUE(1, 6)), -- Vendedor entre los 5 creados
         CURRENT_TIMESTAMP - DBMS_RANDOM.VALUE(1, 365),
         rec.precio_base * 0.95,        -- Descuento del 5%
         CASE TRUNC(DBMS_RANDOM.VALUE(1, 4))
            WHEN 1 THEN 'Contado' WHEN 2 THEN 'Financiado' ELSE 'Leasing' END
      );
   END LOOP;
END;
