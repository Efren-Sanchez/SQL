-- 2. DEFINICIÓN DEL ESQUEMA (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE marcas (
    id_marca      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(50) NOT NULL,
    pais_origen   VARCHAR2(50)
);

CREATE TABLE modelos (
    id_modelo     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_marca      NUMBER NOT NULL,
    nombre        VARCHAR2(50) NOT NULL,
    segmento      VARCHAR2(20) NOT NULL,
    CONSTRAINT chk_segmento CHECK (segmento IN ('SUV', 'Sedán', 'Compacto', 'Deportivo', 'Pick-up', 'Eléctrico')),
    CONSTRAINT fk_modelo_marca FOREIGN KEY (id_marca) REFERENCES marcas(id_marca)
);

CREATE TABLE coches (
    id_coche      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo     NUMBER NOT NULL,
    vin           VARCHAR2(17) UNIQUE NOT NULL,
    color         VARCHAR2(30),
    anio          NUMBER(4) NOT NULL,
    precio_base   NUMBER(12,2) NOT NULL,
    estado        VARCHAR2(20) DEFAULT 'Disponible',
    tipo          VARCHAR2(10) DEFAULT 'Nuevo',
    kilometraje   NUMBER DEFAULT 0,
    CONSTRAINT chk_estado CHECK (estado IN ('Disponible', 'Reservado', 'Vendido', 'Mantenimiento')),
    CONSTRAINT chk_tipo CHECK (tipo IN ('Nuevo', 'Ocasión')),
    CONSTRAINT fk_coche_modelo FOREIGN KEY (id_modelo) REFERENCES modelos(id_modelo)
);

CREATE TABLE clientes (
    id_cliente    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(50) NOT NULL,
    apellidos     VARCHAR2(100) NOT NULL,
    dni           VARCHAR2(15) UNIQUE NOT NULL,
    telefono      VARCHAR2(20),
    email         VARCHAR2(100),
    ciudad        VARCHAR2(50)
);

CREATE TABLE vendedores (
    id_vendedor   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR2(50) NOT NULL,
    apellidos     VARCHAR2(100) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    comision_pct  NUMBER(4,2) DEFAULT 1.00
);

CREATE TABLE ventas (
    id_venta      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_coche      NUMBER NOT NULL,
    id_cliente    NUMBER NOT NULL,
    id_vendedor   NUMBER NOT NULL,
    fecha_venta   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    precio_final  NUMBER(12,2) NOT NULL,
    metodo_pago   VARCHAR2(15) NOT NULL,
    CONSTRAINT chk_pago CHECK (metodo_pago IN ('Contado', 'Financiado', 'Leasing')),
    CONSTRAINT fk_venta_coche FOREIGN KEY (id_coche) REFERENCES coches(id_coche),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    CONSTRAINT fk_venta_vendedor FOREIGN KEY (id_vendedor) REFERENCES vendedores(id_vendedor)
);

CREATE TABLE revisiones (
    id_revision   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_coche      NUMBER NOT NULL,
    fecha_revision DATE NOT NULL,
    descripcion   VARCHAR2(500),
    coste         NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_revision_coche FOREIGN KEY (id_coche) REFERENCES coches(id_coche)
);

