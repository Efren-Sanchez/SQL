-- 2. DDL: DEFINICIÓN DE TABLAS
-- -----------------------------------------------------------------------------

CREATE TABLE pasajeros (
    id_pasajero NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    pasaporte VARCHAR2(20) UNIQUE NOT NULL,
    nacionalidad VARCHAR2(50),
    email VARCHAR2(100) UNIQUE,
    telefono VARCHAR2(20)
);

CREATE TABLE aerolineas (
    id_aerolinea NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    codigo_iata VARCHAR2(3) UNIQUE NOT NULL,
    pais_origen VARCHAR2(50)
);

CREATE TABLE aeropuertos (
    id_aeropuerto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    codigo_iata VARCHAR2(3) UNIQUE NOT NULL,
    ciudad VARCHAR2(50) NOT NULL,
    pais VARCHAR2(50) NOT NULL
);

CREATE TABLE aviones (
    id_avion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo VARCHAR2(50) NOT NULL,
    capacidad_pasajeros NUMBER NOT NULL,
    id_aerolinea NUMBER NOT NULL,
    CONSTRAINT fk_avion_aerolinea FOREIGN KEY (id_aerolinea) REFERENCES aerolineas(id_aerolinea) ON DELETE CASCADE
);

CREATE TABLE vuelos (
    id_vuelo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_vuelo VARCHAR2(10) UNIQUE NOT NULL,
    id_aerolinea NUMBER NOT NULL,
    id_origen NUMBER NOT NULL,
    id_destino NUMBER NOT NULL,
    id_avion NUMBER NOT NULL,
    fecha_salida DATE NOT NULL,
    fecha_llegada DATE NOT NULL,
    estado VARCHAR2(20) DEFAULT 'Programado',
    precio_base NUMBER(10,2) NOT NULL,
    CONSTRAINT chk_estado_vuelo CHECK (estado IN ('Programado', 'En Vuelo', 'Aterrizado', 'Retrasado', 'Cancelado')),
    CONSTRAINT fk_vuelo_aerolinea FOREIGN KEY (id_aerolinea) REFERENCES aerolineas(id_aerolinea),
    CONSTRAINT fk_vuelo_origen FOREIGN KEY (id_origen) REFERENCES aeropuertos(id_aeropuerto),
    CONSTRAINT fk_vuelo_destino FOREIGN KEY (id_destino) REFERENCES aeropuertos(id_aeropuerto),
    CONSTRAINT fk_vuelo_avion FOREIGN KEY (id_avion) REFERENCES aviones(id_avion)
);

CREATE TABLE reservas (
    id_reserva NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pasajero NUMBER NOT NULL,
    id_vuelo NUMBER NOT NULL,
    fecha_reserva TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    asiento VARCHAR2(5) NOT NULL,
    clase VARCHAR2(20) DEFAULT 'Turista',
    precio_final NUMBER(10,2) NOT NULL,
    CONSTRAINT chk_clase_reserva CHECK (clase IN ('Turista', 'Business', 'Primera')),
    CONSTRAINT fk_reserva_pasajero FOREIGN KEY (id_pasajero) REFERENCES pasajeros(id_pasajero),
    CONSTRAINT fk_reserva_vuelo FOREIGN KEY (id_vuelo) REFERENCES vuelos(id_vuelo)
);

CREATE TABLE equipaje (
    id_equipaje NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva NUMBER NOT NULL,
    peso_kg NUMBER(5,2) NOT NULL,
    tipo VARCHAR2(20) DEFAULT 'Bodega',
    CONSTRAINT chk_tipo_equipaje CHECK (tipo IN ('Mano', 'Bodega')),
    CONSTRAINT fk_equipaje_reserva FOREIGN KEY (id_reserva) REFERENCES reservas(id_reserva) ON DELETE CASCADE
);

