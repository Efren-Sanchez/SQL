-- 4. CONSULTAS DE PRUEBA
-- -----------------------------------------------------------------------------

-- 1. INFORME MAESTRO
SELECT 
    v.numero_vuelo, 
    a.nombre AS aerolinea,
    p.nombre || ' ' || p.apellidos AS pasajero,
    r.asiento,
    r.clase,
    ao.codigo_iata AS origen,
    ad.codigo_iata AS destino
FROM reservas r
JOIN pasajeros p ON r.id_pasajero = p.id_pasajero
JOIN vuelos v ON r.id_vuelo = v.id_vuelo
JOIN aerolineas a ON v.id_aerolinea = a.id_aerolinea
JOIN aeropuertos ao ON v.id_origen = ao.id_aeropuerto
JOIN aeropuertos ad ON v.id_destino = ad.id_aeropuerto
ORDER BY v.numero_vuelo;

-- 2. TABLÓN DE ANUNCIOS (Uso de FETCH FIRST en lugar de LIMIT)
SELECT 
    v.numero_vuelo, 
    a.nombre AS aerolinea, 
    o.ciudad AS ciudad_origen, 
    d.ciudad AS ciudad_destino, 
    v.fecha_salida, 
    v.estado
FROM vuelos v
JOIN aerolineas a ON v.id_aerolinea = a.id_aerolinea
JOIN aeropuertos o ON v.id_origen = o.id_aeropuerto
JOIN aeropuertos d ON v.id_destino = d.id_aeropuerto
ORDER BY v.fecha_salida ASC
FETCH FIRST 20 ROWS ONLY;

-- 3. ESTADÍSTICAS FINANCIERAS
SELECT 
    a.nombre AS aerolinea, 
    COUNT(r.id_reserva) AS total_pasajeros,
    SUM(r.precio_final) AS ingresos_totales
FROM aerolineas a
JOIN vuelos v ON a.id_aerolinea = v.id_aerolinea
JOIN reservas r ON v.id_vuelo = r.id_vuelo
GROUP BY a.id_aerolinea, a.nombre
HAVING SUM(r.precio_final) > 0
ORDER BY ingresos_totales DESC;

-- 4. CÁLCULO DE DURACIÓN (En Oracle, la resta de fechas da días, multiplicamos para horas)
SELECT 
    numero_vuelo, 
    fecha_salida, 
    fecha_llegada,
    ROUND((fecha_llegada - fecha_salida) * 24, 2) || ' Horas' AS duracion_estimada
FROM vuelos
WHERE (fecha_llegada - fecha_salida) * 24 > 3;

-- 5. CONTROL DE VOLUMEN TOTAL
SELECT 'Aerolineas' as Tabla, COUNT(*) as Total FROM aerolineas
UNION ALL SELECT 'Aeropuertos', COUNT(*) FROM aeropuertos
UNION ALL SELECT 'Pasajeros', COUNT(*) FROM pasajeros
UNION ALL SELECT 'Vuelos', COUNT(*) FROM vuelos
UNION ALL SELECT 'Reservas', COUNT(*) FROM reservas;
