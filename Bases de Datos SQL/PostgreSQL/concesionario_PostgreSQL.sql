-- 1. LIMPIEZA E INICIALIZACIÓN
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS revisiones CASCADE;
DROP TABLE IF EXISTS ventas CASCADE;
DROP TABLE IF EXISTS coches CASCADE;
DROP TABLE IF EXISTS modelos CASCADE;
DROP TABLE IF EXISTS marcas CASCADE;
DROP TABLE IF EXISTS vendedores CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;

-- Borrado de tipos ENUM si ya existen
DROP TYPE IF EXISTS tipo_segmento;
DROP TYPE IF EXISTS tipo_estado;
DROP TYPE IF EXISTS tipo_vehiculo;
DROP TYPE IF EXISTS tipo_pago;

-- 2. DEFINICIÓN DE TIPOS ENUM (Personalizados en Postgres)
-- -----------------------------------------------------------------------------
CREATE TYPE tipo_segmento AS ENUM ('SUV', 'Sedán', 'Compacto', 'Deportivo', 'Pick-up', 'Eléctrico');
CREATE TYPE tipo_estado AS ENUM ('Disponible', 'Reservado', 'Vendido', 'Mantenimiento');
CREATE TYPE tipo_vehiculo AS ENUM ('Nuevo', 'Ocasión');
CREATE TYPE tipo_pago AS ENUM ('Contado', 'Financiado', 'Leasing');

-- 3. DEFINICIÓN DEL ESQUEMA (DDL)
-- -----------------------------------------------------------------------------

CREATE TABLE marcas (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    pais_origen VARCHAR(50)
);

CREATE TABLE modelos (
    id_modelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_marca INTEGER NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    segmento tipo_segmento NOT NULL,
    CONSTRAINT fk_modelo_marca FOREIGN KEY (id_marca) REFERENCES marcas(id_marca)
);

CREATE TABLE coches (
    id_coche INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo INTEGER NOT NULL,
    vin VARCHAR(17) UNIQUE NOT NULL,
    color VARCHAR(30),
    anio INTEGER NOT NULL,
    precio_base DECIMAL(12,2) NOT NULL,
    estado tipo_estado DEFAULT 'Disponible',
    tipo tipo_vehiculo DEFAULT 'Nuevo',
    kilometraje INTEGER DEFAULT 0,
    CONSTRAINT fk_coche_modelo FOREIGN KEY (id_modelo) REFERENCES modelos(id_modelo)
);

CREATE TABLE clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni VARCHAR(15) UNIQUE NOT NULL,
    telefono VARCHAR(20),
    email VARCHAR(100),
    ciudad VARCHAR(50)
);

CREATE TABLE vendedores (
    id_vendedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    comision_pct DECIMAL(4,2) DEFAULT 1.00
);

CREATE TABLE ventas (
    id_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_coche INTEGER NOT NULL,
    id_cliente INTEGER NOT NULL,
    id_vendedor INTEGER NOT NULL,
    fecha_venta TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    precio_final DECIMAL(12,2) NOT NULL,
    metodo_pago tipo_pago NOT NULL,
    CONSTRAINT fk_venta_coche FOREIGN KEY (id_coche) REFERENCES coches(id_coche),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    CONSTRAINT fk_venta_vendedor FOREIGN KEY (id_vendedor) REFERENCES vendedores(id_vendedor)
);

CREATE TABLE revisiones (
    id_revision INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_coche INTEGER NOT NULL,
    fecha_revision DATE NOT NULL,
    descripcion TEXT,
    coste DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_revision_coche FOREIGN KEY (id_coche) REFERENCES coches(id_coche)
);

