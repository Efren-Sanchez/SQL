-- 5. CONSULTAS DE PRUEBA (Análisis de datos)
-- -----------------------------------------------------------------------------

-- A. Reporte de ventas: ¿Qué hemos vendido y quién lo ha vendido?
SELECT 
    v.fecha_venta::date, 
    ma.nombre AS marca, 
    mo.nombre AS modelo, 
    cl.nombre || ' ' || cl.apellidos AS cliente,
    ve.nombre AS vendedor,
    v.precio_final
FROM ventas v
JOIN coches c ON v.id_coche = c.id_coche
JOIN modelos mo ON c.id_modelo = mo.id_modelo
JOIN marcas ma ON mo.id_marca = ma.id_marca
JOIN clientes cl ON v.id_cliente = cl.id_cliente
JOIN vendedores ve ON v.id_vendedor = ve.id_vendedor
ORDER BY v.fecha_venta DESC
LIMIT 10;

-- B. Inventario actual por estado
SELECT estado, COUNT(*) as cantidad, ROUND(AVG(precio_base), 2) as precio_promedio
FROM coches
GROUP BY estado;

-- C. Top 3 Clientes que más han invertido (incluyendo mantenimiento)
SELECT 
    cl.nombre, 
    cl.apellidos, 
    SUM(v.precio_final) as total_compra
FROM clientes cl
JOIN ventas v ON cl.id_cliente = v.id_cliente
GROUP BY cl.id_cliente, cl.nombre, cl.apellidos
ORDER BY total_compra DESC
LIMIT 3;

-- D. Coches con mayor coste acumulado en revisiones
SELECT c.vin, mo.nombre, COUNT(r.id_revision) as num_revisiones, SUM(r.coste) as coste_total
FROM revisiones r
JOIN coches c ON r.id_coche = c.id_coche
JOIN modelos mo ON c.id_modelo = mo.id_modelo
GROUP BY c.id_coche, c.vin, mo.nombre
HAVING SUM(r.coste) > 500
ORDER BY coste_total DESC;